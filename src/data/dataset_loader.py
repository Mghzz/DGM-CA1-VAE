"""Dataset loader module for VAE assignment.

Loads data generated by original dataset.py without modifying its generation logic.
Recovers the true correspondence between 20D observations x, 2D source coordinates s,
and cluster labels y, accounting for the permutation applied in dataset.py.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Optional, Tuple
import runpy
import numpy as np
import torch
from torch.utils.data import DataLoader, Dataset


@dataclass
class DatasetSplits:
    """Container for train, validation, and test splits with ground-truth coordinates."""
    # 20D normalized observations
    x_train: np.ndarray
    x_val: np.ndarray
    x_test: np.ndarray
    # Cluster labels (0 to 7) - FOR EVALUATION/VISUALIZATION ONLY
    y_train: np.ndarray
    y_val: np.ndarray
    y_test: np.ndarray
    # 2D source coordinates aligned with x and y
    s_train: np.ndarray
    s_val: np.ndarray
    s_test: np.ndarray
    # Generation metadata
    centers: np.ndarray
    mean: np.ndarray
    std: np.ndarray
    order: np.ndarray


class VAEDataset(Dataset):
    """PyTorch Dataset wrapper for VAE observations.
    
    CRITICAL RULE:
    y (cluster labels) is strictly for evaluation/analysis and must NEVER be used
    as model inputs or optimization targets.
    """

    def __init__(
        self,
        x: np.ndarray,
        y: Optional[np.ndarray] = None,
        s: Optional[np.ndarray] = None,
    ):
        self.x = torch.from_numpy(x).float()
        self.y = torch.from_numpy(y).long() if y is not None else None
        self.s = torch.from_numpy(s).float() if s is not None else None

    def __len__(self) -> int:
        return len(self.x)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        item = {"x": self.x[idx]}
        if self.y is not None:
            item["y"] = self.y[idx]
        if self.s is not None:
            item["s"] = self.s[idx]
        return item


# Singleton cache to avoid re-running dataset.py multiple times
_CACHED_DATASET: Optional[DatasetSplits] = None


def load_dataset(dataset_script_path: Optional[Path] = None) -> DatasetSplits:
    """Executes dataset.py and extracts aligned splits, restoring s alignment.
    
    Args:
        dataset_script_path: Path to dataset.py. If None, resolves relative to project root.
        
    Returns:
        DatasetSplits instance containing all splits and aligned coordinates.
    """
    global _CACHED_DATASET
    if _CACHED_DATASET is not None:
        return _CACHED_DATASET

    if dataset_script_path is None:
        dataset_script_path = Path(__file__).resolve().parent.parent.parent / "dataset.py"

    if not dataset_script_path.exists():
        raise FileNotFoundError(f"dataset.py not found at {dataset_script_path}")

    # Execute original dataset.py in an isolated namespace without modifying it
    scope = runpy.run_path(str(dataset_script_path))

    x_train = scope["x_train"]
    x_val = scope["x_val"]
    x_test = scope["x_test"]
    y_train = scope["y_train"]
    y_val = scope["y_val"]
    y_test = scope["y_test"]
    order = scope["order"]
    s_raw = scope["s"]
    centers = scope["centers"]
    mean = scope["mean"]
    std = scope["std"]

    # In dataset.py, x and labels were permuted by 'order', but 's' was not.
    # Applying the same permutation to 's' restores exact 1-to-1 sample correspondence.
    s_permuted = s_raw[order]

    n_train = len(x_train)
    n_val = len(x_val)

    s_train = s_permuted[:n_train]
    s_val = s_permuted[n_train:n_train + n_val]
    s_test = s_permuted[n_train + n_val:]

    _CACHED_DATASET = DatasetSplits(
        x_train=x_train,
        x_val=x_val,
        x_test=x_test,
        y_train=y_train,
        y_val=y_val,
        y_test=y_test,
        s_train=s_train,
        s_val=s_val,
        s_test=s_test,
        centers=centers,
        mean=mean,
        std=std,
        order=order,
    )

    return _CACHED_DATASET


def get_dataloaders(
    batch_size: int = 256,
    dataset_script_path: Optional[Path] = None,
    num_workers: int = 0,
    shuffle_train: bool = True,
    seed: Optional[int] = None,
) -> Tuple[DataLoader, DataLoader, DataLoader, DatasetSplits]:
    """Builds PyTorch DataLoaders for train, validation, and test splits.
    
    REPRODUCIBILITY CONTRACT:
    To guarantee full experiment reproducibility across runs:
    1. Call set_seed(training_seed) BEFORE creating the model to initialize
       network weights and learnable prior centers identically.
    2. Pass seed=training_seed to get_dataloaders() (or rely on the seeded global RNG)
       so the training DataLoader's mini-batch shuffle sequence is strictly reproducible.
    3. Do NOT reseed the global RNG inside every training epoch, allowing multi-epoch
       mini-batch permutations to evolve naturally and deterministically.
    4. Validation uses a dedicated isolated generator and preserves the training RNG state.
    
    Args:
        batch_size: Mini-batch size (PDF specifies 256).
        dataset_script_path: Path to dataset.py.
        num_workers: Worker processes for data loading.
        shuffle_train: Whether to shuffle training mini-batches.
        seed: Optional training seed to govern DataLoader shuffle sequence.
        
    Returns:
        Tuple of (train_loader, val_loader, test_loader, splits).
    """
    splits = load_dataset(dataset_script_path)

    train_ds = VAEDataset(splits.x_train, splits.y_train, splits.s_train)
    val_ds = VAEDataset(splits.x_val, splits.y_val, splits.s_val)
    test_ds = VAEDataset(splits.x_test, splits.y_test, splits.s_test)

    train_gen = torch.Generator().manual_seed(seed) if seed is not None else None
    val_gen = torch.Generator()
    test_gen = torch.Generator()

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=shuffle_train,
        generator=train_gen,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=batch_size,
        shuffle=False,
        generator=val_gen,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
    )
    test_loader = DataLoader(
        test_ds,
        batch_size=batch_size,
        shuffle=False,
        generator=test_gen,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
    )

    return train_loader, val_loader, test_loader, splits
